using Alissa.Core.Interfaces;

namespace Alissa.Core.Services
{
    /// <summary>
    /// Service for integrating Alissa into external programs and modifying code.
    /// </summary>
    public class CodeIntegrationService : ICodeIntegrationService
    {
        // Constants
        private const string BACKUPS_DIR = "backups";
        private const string CONFIG_DIR = "config";
        private const string MEMORY_DIR = "memory";
        private const string LOGS_DIR = "logs";
        private const string BACKUP_TIMESTAMP_FORMAT = "yyyy-MM-dd_HH-mm-ss";
        private const string BACKUP_EXTENSION = ".bak";
        private const string DEFAULT_LANGUAGE = "csharp";

        private readonly string _basePath;
        private readonly string _backupPath;
        private readonly HashSet<string> _protectedPaths;

        public CodeIntegrationService(string basePath)
        {
            _basePath = basePath;
            _backupPath = Path.Combine(basePath, BACKUPS_DIR);
            _protectedPaths = new HashSet<string>
            {
                Path.Combine(basePath, CONFIG_DIR),
                Path.Combine(basePath, MEMORY_DIR),
                Path.Combine(basePath, LOGS_DIR)
            };

            Directory.CreateDirectory(_backupPath);
        }

        public async Task<string> ReadCodeFileAsync(string filePath)
        {
            bool fileExists = File.Exists(filePath);

            if (fileExists)
            {
                string content = await File.ReadAllTextAsync(filePath);
                return content;
            }

            return string.Empty;
        }

