        public async Task WriteModificationAsync(string filePath, string modifiedCode)
        {
            bool isSafe = await IsFileSafeToModifyAsync(filePath);

            if (isSafe)
            {
                await File.WriteAllTextAsync(filePath, modifiedCode);
            }

            await Task.CompletedTask;
        }

        public async Task<bool> IsFileSafeToModifyAsync(string filePath)
        {
            bool isNullOrEmpty = string.IsNullOrWhiteSpace(filePath);

            if (isNullOrEmpty)
            {
                return await Task.FromResult(false);
            }

            bool isProtected = IsPathProtected(filePath);
            bool isSafe = !isProtected;

            return await Task.FromResult(isSafe);
        }

        public bool IsPathProtected(string filePath)
        {
            bool isNullOrEmpty = string.IsNullOrWhiteSpace(filePath);

            if (isNullOrEmpty)
            {
                return true;
            }

            bool isProtected = false;

            for (int i = 0; i < _protectedPaths.Count; i++)
            {
                string protectedPath = _protectedPaths.ElementAt(i);
                bool pathStartsWithProtected = filePath.StartsWith(protectedPath, StringComparison.OrdinalIgnoreCase);

                if (pathStartsWithProtected)
                {
                    isProtected = true;
                    break;
                }
            }

            return isProtected;
        }

        public async Task<string> CreateBackupAsync(string filePath)
        {
            bool fileExists = File.Exists(filePath);

            if (fileExists)
            {
                string fileName = Path.GetFileName(filePath);
                string timestamp = DateTime.Now.ToString(BACKUP_TIMESTAMP_FORMAT);
                string backupPath = Path.Combine(_backupPath, $"{fileName}.{timestamp}{BACKUP_EXTENSION}");

                string originalContent = await File.ReadAllTextAsync(filePath);
                await File.WriteAllTextAsync(backupPath, originalContent);

                return backupPath;
            }

            return string.Empty;
        }
    }
}
